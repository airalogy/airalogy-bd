import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';

export async function exerciseRemoteTasks({rpc,call,web,request,okay,admin,editor,viewer,direct,draftToken,clearRate}) {
  clearRate();
  const matter='project-demo-partnership', hidden='project-demo-investment';
  const get=(operation,extra={},member=editor)=>request('/api/workspace?'+new URLSearchParams({action:'tasks',operation,project_id:matter,...extra}),null,member);
  const read=id=>call('read_task',{matter_id:matter,...(id?{id}:{})},direct.token);
  const original=await call('read_progress',{matter_id:matter,progress_id:'2026-01-15-solution-meeting'},direct.token);
  const tools=(await (await rpc('tools/list',{},draftToken.token)).json()).result.tools.map(t=>t.name);
  for(const name of ['search_tasks','read_task','task_assignees','task_history','submit_task'])assert.ok(tools.includes(name));
  assert.ok(!tools.includes('save_task'));
  const assignees=await call('task_assignees',{matter_id:matter},direct.token);
  assert.ok(assignees.items.some(a=>a.id===editor.user.id));
  assert.ok(!assignees.items.some(a=>a.id===viewer.user.id));
  assert.ok(assignees.items.every(a=>Object.keys(a).sort().join(',')==='id,name'));
  const args={matter_id:matter,revision:(await read()).revision,request_id:randomUUID(),changes:{title:'整理部署资料',body:'## 说明\n\n- 补齐需求清单',assignee_id:editor.user.id,due_date:'2026-11-20',source_progress_id:'2026-01-15-solution-meeting'}};
  const draft=await call('submit_task',args,draftToken.token);
  assert.equal((await okay(await get('list'))).total,0);
  const pending=(await okay(await request('/api/remote?action=drafts',null,admin))).drafts.find(d=>d.id===draft.draftId);
  assert.equal(pending.operation,'add_task');
  assert.equal(pending.changes.find(c=>c.field==='assignee_id').after,editor.user.name);
  const saved=await okay(await web('confirm',{draftId:draft.draftId,confirmed:true}));
  const current=await read(saved.id);
  assert.equal(current.record.author.id,admin.user.id);
  assert.equal((await okay(await get('list',{scope:'mine'}))).items[0].id,saved.id);
  const body={action:'tasks',operation:'save',project_id:matter,id:saved.id,revision:current.revision,request_id:randomUUID(),payload:{...current.fields,state:'completed',completion_note:'资料已整理并发送。'}};
  assert.equal((await request('/api/workspace',body,editor,{'X-BD-CSRF':'wrong'})).status,403);
  assert.equal((await request('/api/workspace',body,viewer)).status,403);
  assert.equal((await get('list',{},null)).status,401);
  const completed=await okay(await request('/api/workspace',body,editor));
  assert.deepEqual(await okay(await request('/api/workspace',body,editor)),completed);
  const after=await read(saved.id);assert.equal(after.record.completed_by.id,editor.user.id);
  assert.equal(after.record.author.id,admin.user.id);assert.equal(after.record.updated_by.id,editor.user.id);
  assert.equal((await okay(await get('list'))).total,0);
  assert.equal((await okay(await get('list',{state:'completed'}))).total,1);
  assert.deepEqual((await call('read_progress',{matter_id:matter,progress_id:'2026-01-15-solution-meeting'},direct.token)).fields,original.fields);
  const history=await call('task_history',{matter_id:matter,id:saved.id},direct.token);
  assert.equal(history.versions.length,2);
  assert.equal((await okay(await get('read',{id:saved.id,snapshot:saved.status.version}))).record.state,'pending');
  assert.equal((await okay(await get('version',{id:saved.id,version:completed.status.version}))).record.completion_note,'资料已整理并发送。');
  assert.equal((await get('read',{project_id:hidden,id:saved.id})).status,403);
  const hiddenArgs={matter_id:hidden,revision:(await call('read_task',{matter_id:hidden},direct.token)).revision,request_id:randomUUID(),changes:{title:'受限事项的待办'}};
  await call('save_task',hiddenArgs,direct.token);
  assert.equal((await okay(await request('/api/workspace?action=tasks&operation=list&state=all',null,editor))).total,1);
  assert.equal((await okay(await request('/api/workspace?action=tasks&operation=list&state=all&query=受限事项',null,editor))).total,0);
  const stale={matter_id:matter,id:saved.id,revision:current.revision,request_id:randomUUID(),changes:{state:'pending'}};
  assert.equal((await call('save_task',stale,direct.token,true)).code,'conflict');
  assert.equal((await get('list',{state:'invalid'})).status,422);
  assert.equal((await request('/api/workspace?'+new URLSearchParams({action:'tasks',operation:'save',project_id:matter}),null,editor)).status,403);
  const reopen={...stale,revision:after.revision,request_id:randomUUID()};
  const reopened=await call('save_task',reopen,direct.token);
  assert.deepEqual(await call('save_task',reopen,direct.token),reopened);
  assert.equal((await read(saved.id)).record.completed_at,null);
  clearRate();
}
