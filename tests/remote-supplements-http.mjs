import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';

export async function exerciseRemoteSupplements({rpc,call,web,request,okay,admin,editor,viewer,direct,draftToken,clearRate}) {
  clearRate();
  const target={matter_id:'project-demo-partnership',meeting_id:'2026-01-15-solution-meeting'};
  const query=new URLSearchParams({action:'supplements',project_id:target.matter_id,event_id:target.meeting_id});
  const read=()=>call('read_meeting_supplements',target,direct.token);
  const original=await call('read_progress',{matter_id:target.matter_id,progress_id:target.meeting_id},direct.token);
  const names=(await (await rpc('tools/list',{},draftToken.token)).json()).result.tools.map(t=>t.name);
  assert.ok(names.includes('read_meeting_supplements'));assert.ok(names.includes('submit_meeting_supplement'));assert.ok(!names.includes('save_meeting_supplement'));
  const args={...target,revision:(await read()).revision,request_id:randomUUID(),changes:{date:'2026-11-11',title:'会后介绍草稿',body:'## 平台简介\n\n面向行业的完整文案。\n\n- 保留 Markdown 列表'}};
  const draft=await call('submit_meeting_supplement',args,draftToken.token);
  assert.equal((await read()).items.length,0);
  const pending=(await okay(await request('/api/remote?action=drafts',null,admin))).drafts.find(d=>d.id===draft.draftId);
  assert.equal(pending.operation,'add_supplement');
  const saved=await okay(await web('confirm',{draftId:draft.draftId,confirmed:true}));
  const current=await call('read_meeting_supplements',{...target,id:saved.id},direct.token);
  assert.equal(current.record.author.id,admin.user.id);
  assert.equal(current.record.body,args.changes.body);
  const list=await okay(await request('/api/workspace?'+query,null,editor));
  assert.equal(list.items[0].id,saved.id);
  const changed=await okay(await request('/api/workspace',{action:'supplements',operation:'save',project_id:target.matter_id,event_id:target.meeting_id,id:saved.id,revision:current.revision,request_id:randomUUID(),payload:{...args.changes,body:'编辑成员完善文案。'}},editor));
  const revised=await call('read_meeting_supplements',{...target,id:saved.id},direct.token);
  assert.equal(revised.record.author.id,admin.user.id);
  assert.equal(revised.record.updated_by.id,editor.user.id);
  const history=await call('meeting_supplement_history',{...target,id:saved.id},direct.token);
  assert.equal(history.versions.length,2);
  assert.equal((await call('meeting_supplement_history',{...target,id:saved.id,version:saved.status.version},direct.token)).record.body,args.changes.body);
  assert.equal((await okay(await request('/api/workspace?'+query+'&snapshot='+saved.status.version,null,editor))).items[0].body,args.changes.body);
  assert.equal((await request('/api/workspace',{action:'supplements',operation:'save',project_id:target.matter_id,event_id:target.meeting_id},viewer)).status,403);
  assert.equal((await request('/api/workspace?'+query.toString().replace(target.matter_id,'project-demo-investment'),null,editor)).status,403);
  assert.equal((await request('/api/workspace?'+query,null,null)).status,401);
  assert.equal((await request('/api/workspace',{action:'supplements',operation:'save',project_id:target.matter_id,event_id:target.meeting_id},editor,{'X-BD-CSRF':'invalid'})).status,403);
  const directArgs={...target,revision:(await read()).revision,request_id:randomUUID(),changes:{date:'2026-11-12',body:'另一条独立补充'}};
  const directResult=await call('save_meeting_supplement',directArgs,direct.token);
  assert.deepEqual(await call('save_meeting_supplement',directArgs,direct.token),directResult);
  assert.equal((await read()).items.length,2);
  const stale={...target,id:saved.id,revision:current.revision,request_id:randomUUID(),changes:{body:'过期编辑'}};
  assert.equal((await call('save_meeting_supplement',stale,direct.token,true)).code,'conflict');
  const after=await call('read_progress',{matter_id:target.matter_id,progress_id:target.meeting_id},direct.token);
  assert.deepEqual(after.fields,original.fields);
  assert.equal(changed.id,saved.id);
  clearRate();
}
