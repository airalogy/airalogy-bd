import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {DatabaseSync} from 'node:sqlite';

export async function exerciseProgressPeople({directory,request,okay,admin,editor,viewer}) {
  const matter='project-demo-partnership', hidden='project-demo-investment', endpoint='/api/workspace';
  const people=()=>readFileSync(path.join(directory,'content/people.yaml'),'utf8');
  const hiddenBody=readFileSync(path.join(directory,'content/counterparties/星帆创投/matters/融资对接/README.md'),'utf8');
  const db=new DatabaseSync(path.join(directory,'.bd-auth/accounts.sqlite3'));
  const accountCount=db.prepare('SELECT count(*) n FROM users').get().n;
  const opened=await okay(await request(endpoint+'?action=record&kind=progress&id=&project_id='+matter,null,editor));
  const profile={name:'程夏',affiliation:'示例研究室',phone:'001-200',wechat:null,email:'chengxia@example.invalid'};
  const payload={date:'2026-10-30',type:'meeting',title:'编辑成员新增联系人',summary:'交流示例需求。',importance:'normal',participants:[profile.name],body:'交流示例需求。',location:'线上',new_people:[profile],new_contacts:[{person_id:profile.name,side:'counterparty',project_roles:['participant'],notes:'本次交流参与人'}]};
  const save={action:'save',kind:'progress',id:'',project_id:matter,revision:opened.revision,payload};
  const baseline=people();
  assert.equal((await request(endpoint,{...save,action:'preview'},editor)).status,403,'Web routes do not expose internal previews');
  assert.equal(people(),baseline,'Preview must not persist any profile');
  for(const [member,patch,status] of [[viewer,{},403],[editor,{project_id:hidden},403]]) assert.equal((await request(endpoint,{...save,...patch},member)).status,status);
  assert.equal((await request(endpoint,save,editor,{'X-BD-CSRF':'forged'})).status,403);
  const bad=await request(endpoint,{...save,payload:{...payload,new_people:[{...profile,email:'invalid'}]}},editor);
  assert.equal(bad.status,422);
  const deniedAttachment=await request(endpoint,{...save,attachments:[{mode:'existing',file_id:'private-or-missing',version_id:'v1',revision:'invalid'}]},editor);
  assert.ok([403,422].includes(deniedAttachment.status));
  assert.equal(people(),baseline,'Validation and attachment failure must leave no orphan profile');
  const hiddenPerson={...payload,participants:['宋禾'],new_people:[{...profile,name:'宋禾'}],new_contacts:[{...payload.new_contacts[0],person_id:'宋禾'}]};
  const collision=await request(endpoint,{...save,payload:hiddenPerson},editor);
  assert.equal(collision.status,409);const collisionText=await collision.text();
  assert.doesNotMatch(collisionText,/星帆|投资经理|songhe|example\.invalid/);
  assert.equal((await request(endpoint,{...save,payload:{...hiddenPerson,new_people:[]}},editor)).status,403);
  assert.equal((await request(endpoint,{...save,payload:{...payload,new_people:[{...profile,id:'宋禾'}]}},editor)).status,422);
  assert.equal((await request(endpoint,{...save,payload:{...payload,new_contacts:[]}},editor)).status,422);
  assert.equal((await request(endpoint,{...save,payload:{...payload,participants:[{}]}},editor)).status,422);
  assert.equal((await request(endpoint,{...save,payload:{...payload,new_people:[{...profile,role:'admin'}]}},editor)).status,422);
  const matterRecord=await okay(await request(endpoint+'?action=record&kind=project&id='+matter,null,editor));
  assert.equal((await request(endpoint,{action:'save',kind:'project',id:matter,revision:matterRecord.revision,payload:{...matterRecord.record.metadata,contacts:matterRecord.record.contacts,body:matterRecord.record.body,new_people:[profile]}},editor)).status,403);
  assert.equal(people(),baseline);
  const saved=await okay(await request(endpoint,save,editor));
  const loaded=await okay(await request(endpoint+'?action=record&kind=progress&id='+saved.id+'&project_id='+matter,null,editor));
  assert.deepEqual(loaded.record.event.participants,[profile.name]);
  const view=await okay(await request(endpoint+'?action=workspace',null,editor));
  assert.equal(view.data.people.find(p=>p.id===profile.name).phone,profile.phone);
  assert.equal(view.data.people.some(p=>p.id==='宋禾'),false);
  assert.equal(view.data.projects.find(p=>p.id===matter).contacts.some(c=>c.person_id===profile.name),true);
  assert.equal((await request(endpoint+'?action=record&kind=person&id='+encodeURIComponent(profile.name),null,editor)).status,403);
  const history=await okay(await request(endpoint+'?action=history&kind=person&id='+encodeURIComponent(profile.name),null,admin));
  assert.equal(history.versions[0].actor.id,editor.user.id);
  const stale={...payload,participants:['程秋'],new_people:[{...profile,name:'程秋'}],new_contacts:[{...payload.new_contacts[0],person_id:'程秋'}]};
  assert.equal((await request(endpoint,{...save,payload:stale},editor)).status,409);
  assert.doesNotMatch(people(),/程秋/);
  const current=await okay(await request(endpoint+'?action=record&kind=progress&id=&project_id='+matter,null,editor));
  assert.equal((await request(endpoint,{...save,revision:current.revision},editor)).status,409,'Same-name replay cannot overwrite an existing profile');
  assert.equal(readFileSync(path.join(directory,'content/counterparties/星帆创投/matters/融资对接/README.md'),'utf8'),hiddenBody);
  assert.equal(db.prepare('SELECT count(*) n FROM users').get().n,accountCount,'Business contacts never create login accounts');
  db.close();
}
